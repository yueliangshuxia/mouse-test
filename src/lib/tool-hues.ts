/**
 * 每个工具一个色相。
 *
 * ## 为什么单独一个模块
 *
 * 它原本是 `mouse-repair.astro` 里的一张局部表(那页的索引卡用它),后来首页
 * 也用、现在工具页的标题图标也要用 —— **三个消费者**。再留在页面里的话,
 * 加一件工具就得记得回来改那张表,漏了就是那一格没颜色(而"没颜色"在
 * 这个站上看着像"这一项没做好")。
 *
 * 它**不放进 `tool-motifs.ts`**:那个文件的头一条纪律就是「一律 `currentColor`
 * / 灰阶,**不引入任何色相**」—— 图形本身确实一个颜色都不写,色相是外面那层
 * 底给它的。两件事分开放,才不会让下一个人以为母题可以带色。
 *
 * ## 这是全站唯一一处给纸面加色相的地方
 *
 * 全站的规矩是「纸面走无彩色,有颜色的地方就是在出数」—— **蓝色强调色当年
 * 就是因此被删掉的**。色相破了这条,代价是真实的。几条约束把伤害压到最小:
 *
 * - **只长在图标那一格里**(淡色底 + 彩色描边),正文、边框、数字一概不染
 * - **只出现在"工具的身份标记"上**:标题旁的图标、工具箱的预览格、索引卡
 * - **仪器窗的磷光绿、警告赭黄、故障朱砂仍然是那三个语义位**,没有被顶掉
 * - 换句话说:**读数仍然只有那三种颜色**,多出来的是"这是哪一件工具"这一层
 *
 * ## 挑色
 *
 * 十七个色相彼此拉开(蓝 / 紫 / 琥珀 / 红 / 青 / 翠 / 黄绿 / 粉 / 橙 / 蓝绿 /
 * 玫红 / 靛 / 天蓝 / 紫罗兰 / 黄 / 石板灰 / 绿),**不让相邻两件看着像同一件**。
 * 它们只在**淡底(12%)**和**描边**上用,不铺大面积。
 */
